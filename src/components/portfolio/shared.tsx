import { useEffect, useRef, useState, type ReactNode, type SVGProps } from "react";
import { cn } from "@/lib/utils";

/** Fades content in when it enters the viewport. */
export function Reveal({
  children,
  className,
  delay = 0,
}: {
  children: ReactNode;
  className?: string;
  delay?: number;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    const io = new IntersectionObserver(
      ([entry]) => {
        if (entry?.isIntersecting) {
          setVisible(true);
          io.disconnect();
        }
      },
      { threshold: 0.12 },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      data-visible={visible}
      className={cn("reveal", className)}
      style={{ transitionDelay: `${delay}ms` }}
    >
      {children}
    </div>
  );
}

export function Section({
  id,
  eyebrow,
  title,
  subtitle,
  children,
  className,
}: {
  id: string;
  eyebrow: string;
  title: string;
  subtitle?: string;
  children: ReactNode;
  className?: string;
}) {
  return (
    <section id={id} className={cn("py-20 md:py-24", className)}>
      <div className="mx-auto max-w-6xl px-5 md:px-8">
        <Reveal className="mb-10 max-w-3xl">
          <p className="mb-3 text-xs font-extrabold uppercase tracking-[0.15em] text-primary">
            {eyebrow}
          </p>
          <h2 className="text-4xl font-extrabold tracking-tight md:text-5xl">{title}</h2>
          {subtitle && <p className="mt-4 text-muted-foreground">{subtitle}</p>}
        </Reveal>
        {children}
      </div>
    </section>
  );
}

